/** Techs whose prerequisites are all satisfied. */
export function availableTechs(completed: string[]): Technology[] {
  const done = new Set(completed);
  return TECHNOLOGIES.filter((t) => !done.has(t.id) && t.requires.every((r) => done.has(r)));
}
